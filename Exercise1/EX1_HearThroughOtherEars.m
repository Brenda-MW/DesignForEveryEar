%[text] # Exercise 1: Hear Through Other Ears
%[text] Imagine hearing the same sentence fifty years apart. As we age, high frequencies fade first, and with them consonants like *s, f, th* and *k*. People still hear **that** you are talking, but not **what** you said.
%%
%[text] ## What you will hear
%[text] The app plays speech through four listening effects, plus optional background noise. Try them one at a time.
%[text:table]
%[text] | Effect | What changes | What it feels like |
%[text] | --- | --- | --- |
%[text] | Attenuation | High frequencies fade | Consonants disappear, so words blur |
%[text] | Smearing | Frequency detail blurs | Similar sounds are hard to tell apart |
%[text] | Loudness growth | Loud sounds grow too loud too fast | Turning it up is not the same as clearer |
%[text] | Temporal disruption | Timing detail is jittered | Fast speech is hard to follow |
%[text] | Background noise | Noise is added at a chosen SNR | A busy room makes all of the above worse |
%[text:table]
%%
%[text] ## Try it
%[text] Use headphones at a comfortable volume.
%[text] - Choose **Counting 5-6-7** and click **Play original**.
%[text] - Set **Attenuation** to **Moderate** and click **Play through other ears**. Listen for the *s* in "six" and "seven".
%[text] - Click **Compare spectrograms**. What happened above 4 kHz?
%[text] - Turn on one other effect at a time, then add **Background noise** and lower the SNR. \
%[text] Run this section to open the app.
